// test/objects-types.test.mjs -- typed remotes (#219): `describeRootTypes` (a pure function from what a key may do on a root to `.d.ts` text), the host's `types`
// answer (the allow-lists narrowed by the key, plus an optional host-authored type map that is validated and bounded), and the far side's `rootDescription`.
// The type-level checks of the generated text are in test/types/objects-typed.ts (run by `npm run typecheck`).
import { describe, it, before, afterEach } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createMemoryHost } from '@johnhenry/wsh/memory';
import { generateKeyPair, exportPublicKeySSH } from '@johnhenry/wsh';
import { exposeObjects, createObjectsServer, createObjectsClient, rootDescription } from '@johnhenry/wsh/objects';
import { describeRootTypes, checkTypeText, TYPE_TEXT_LIMITS } from '@johnhenry/wsh/objects-types';
import { createDuplexPair } from './helpers/duplex.mjs';

const rejects = (x, ...rest) => assert.rejects(Promise.resolve(x), ...rest);
const closers = [];
afterEach(async () => { for (const c of closers.splice(0).reverse()) await c().catch(() => {}); });
let keyPair; let keyLine;
before(async () => { keyPair = await generateKeyPair(true); keyLine = await exportPublicKeySSH(keyPair.publicKey); });

const ALLOW = {
  get: ['window.document.title', 'window.app.cart.items', 'window.app.config.**'],
  call: ['window.app.cart.add', 'window.app.makeBus', 'window.app.makeBus().ping', 'window.app.subscribe(callback)'],
  set: ['window.document.title', 'window.app.cart.note'],
  on: ['window.hash@hashchange', 'window.app.bus@ready', 'window.app.makeBus()@ready'],
};
const TYPES = {
  'window.document.title': { value: 'string' },
  'window.app.cart.items': { value: '{ sku: string; qty: number }[]' },
  'window.app.cart.add': { args: '[item: { sku: string; qty?: number }]', result: 'number' },
  'window.hash@hashchange': { data: '{ type: "hashchange"; newURL: string }' },
};
const EVENT_FIELDS = { hashchange: ['newURL', 'oldURL'], '*': ['detail'] };
const description = (extra = {}) => ({ root: 'window', allow: ALLOW, eventFields: EVENT_FIELDS, types: TYPES, ...extra });

describe('describeRootTypes: what the file says', () => {
  const text = describeRootTypes(description(), { name: 'WindowRemote' });

  it('is a declaration file for one exported type, with an import of the helpers and a header that says what it is', () => {
    assert.match(text, /^\/\/ Generated by describeRootTypes/);
    assert.match(text, /import type \{ [^}]*RemoteValue[^}]*RemoteCall[^}]*\} from '@johnhenry\/wsh\/objects';/);
    assert.match(text, /export type WindowRemote = /);
    assert.match(text, /advisory/);
  });

  it('lists the allowed paths and their operations, with the host\'s types where it gave one and unknown where it did not', () => {
    assert.match(text, /readonly title: RemoteValue<string>;/);
    assert.match(text, /WithSet<\{ title: string \}>/, 'a path that may be set carries a typed set');
    assert.match(text, /readonly items: RemoteValue<\{ sku: string; qty: number \}\[\]>/);
    assert.match(text, /readonly add: RemoteCall<\[item: \{ sku: string; qty\?: number \}\], number, unknown>/);
    assert.match(text, /readonly makeBus: RemoteCall<unknown\[\], unknown, \{[^}]*readonly ping: RemoteCall<unknown\[\], unknown, unknown>/s, 'a handle-like result continues with its own members');
    assert.match(text, /readonly subscribe: RemoteCall<unknown\[\], unknown, unknown>/);
    assert.match(text, /WithSet<\{ note: unknown \}>/);
    assert.match(text, /readonly config: RemoteValue<unknown> & \{\s*readonly \[key: string\]: RemoteUntyped;/, 'a wildcard is not guessed at');
  });

  it('events: typed on overloads from allow.on and eventFields, and the host\'s own type for the data where it gave one', () => {
    assert.match(text, /WithEvents<\{ "hashchange": \{ data: \{ type: "hashchange"; newURL: string \}; fields: "detail" \| "newURL" \| "oldURL" \} \}>/);
    assert.match(text, /WithEvents<\{ "ready": \{ data: RemoteEventData<"detail">; fields: "detail" \} \}>/);
  });

  it('is the same text whatever the order of the entries (deterministic)', () => {
    const shuffled = { ...ALLOW, get: [...ALLOW.get].reverse(), call: [...ALLOW.call].reverse(), on: [...ALLOW.on].reverse() };
    assert.equal(describeRootTypes(description({ allow: shuffled }), { name: 'WindowRemote' }), text);
  });
});

describe('describeRootTypes: only what the key may do', () => {
  it('a path that no entry names is not in the file, not even as never; neither is an operation the key was not granted', () => {
    const body = (t) => t.slice(t.indexOf('export type'));
    const text = body(describeRootTypes(description({ allow: { ...ALLOW, get: [...ALLOW.get, 'window.hidden.secret'] }, ops: ['get'], types: { 'window.document.title': { value: 'string' } } })));
    assert.match(text, /title/);
    assert.match(text, /hidden/, 'a get entry that the key holds is there');
    assert.doesNotMatch(text, /RemoteCall/, 'no call signature for a key that may only read');
    assert.doesNotMatch(text, /WithSet|WithEvents/);
    assert.doesNotMatch(text, /add|makeBus|subscribe|note|hashchange|bus/);
    const none = body(describeRootTypes(description({ allow: { get: ['other.thing'], call: [] }, ops: ['get', 'call'], types: {} })));
    assert.doesNotMatch(none, /thing|other/, 'an entry for another root says nothing about this one');
    const without = body(describeRootTypes(description({ allow: { get: ['window.a'], call: ['window.hidden.run'] }, ops: ['get'], types: {} })));
    assert.doesNotMatch(without, /hidden|run/, 'a path that only an operation the key does not hold names is not told');
  });

  it('a type for a path no entry allows is refused, not ignored: the file never says more than the key may do', () => {
    for (const types of [
      { 'window.app.secret': { value: 'string' } },
      { 'window.app.cart.items': { args: '[]' } },
      { 'window.app.cart.add': { value: 'string' } },
      { 'window.app.bus@other': { data: 'string' } },
      { 'window.app.*': { value: 'string' } },
      { 'window.app.cart.add@ready': { data: 'string' } },
    ]) assert.throws(() => describeRootTypes(description({ types })), TypeError, JSON.stringify(types));
    assert.throws(() => describeRootTypes(description({ ops: ['get'], types: { 'window.app.cart.add': { args: '[]' } } })), /no call entry/);
  });

  it('refuses a description that is not what a host sends: odd names, wildcards in event sources, unknown fields, too much', () => {
    const bad = (d, re) => assert.throws(() => describeRootTypes(d), re ?? TypeError);
    bad(null);
    bad({ root: 'a b', allow: {} });
    bad(description({ allow: { get: [5] } }));
    bad(description({ allow: { run: [] } }));
    bad(description({ allow: { on: ['window.a.*@ready'] } }), /named exactly/);
    bad(description({ allow: { on: ['window.a'] } }), /path@type/);
    bad(description({ allow: { get: ['window.a*b'] } }), /whole segment/);
    bad(description({ allow: { get: ['window.\n.x'] } }), /printable/);
    bad(description({ ops: ['get', 'fly'] }));
    bad(description({ eventFields: { x: ['a b'] } }));
    bad(description({ allow: { get: Array.from({ length: 1001 }, (_, i) => `window.a${i}`) } }), /at most/);
    assert.throws(() => describeRootTypes(description(), { name: 'class' }), /usable type name/);
    assert.throws(() => describeRootTypes(description(), { name: 'a b' }), /usable type name/);
    assert.throws(() => describeRootTypes(description(), { name: 'RemoteValue' }), /usable type name/);
  });

  it('a key that the host names oddly cannot put text into the file: a path segment is a quoted name, never code', () => {
    const text = describeRootTypes({ root: 'window', allow: { get: ['window.a b.c"d', 'window.x//y', 'window.\\u0022'] } });
    assert.match(text, /readonly "a b": /);
    assert.match(text, /readonly "c\\"d": /);
    assert.match(text, /readonly "x\/\/y": /);
    const code = text.split('\n').filter((l) => !l.startsWith('//')).join('\n').replace(/"(?:[^"\\]|\\.)*"/g, '""');
    assert.doesNotMatch(code, /\/\/|\/\*/, 'outside a quoted name, the file has no comment opener');
  });
});

describe('the host\'s type text is untrusted: checked as text, never evaluated', () => {
  const ok = ['string', '{ sku: string; qty?: number }[]', '[item: { a: 1 }, ...rest: unknown[]]', 'Promise<Map<string, "a" | "b">>', '(a: number) => void', 'T extends U ? X : Y', 'RemoteHandle<{ n: number }>', '-1 | 2'];
  const refused = [
    ['an import', "import('fs').Stats"],
    ['an import type', 'typeof import("fs")'],
    ['typeof', 'typeof process'],
    ['a line comment', 'string // x'],
    ['a block comment', 'string /* x */'],
    ['a new line (a new declaration)', 'string\ndeclare const x: 1'],
    ['a declaration', 'declare const x: 1'],
    ['a second member', 'string; evil: number'],
    ['a top-level comma', 'string, evil: number'],
    ['a closing brace', 'string } export type X = { a: 1'],
    ['an unclosed bracket', '{ a: string'],
    ['a mismatched bracket', '{ a: string )'],
    ['a template literal', '`a${string}`'],
    ['an escape in a string', '"a\\u0022"'],
    ['a decorator', '@x string'],
    ['a triple slash', '/// <reference path="/etc/passwd" />'],
    ['non-ASCII', 'string declare'],
    ['a tab', 'string\tx'],
    ['empty', '   '],
    ['too long', 'a'.repeat(TYPE_TEXT_LIMITS.maxTextChars + 1)],
    ['too deep', '['.repeat(TYPE_TEXT_LIMITS.maxNesting + 1) + ']'.repeat(TYPE_TEXT_LIMITS.maxNesting + 1)],
    ['a long string literal', `"${'x'.repeat(TYPE_TEXT_LIMITS.maxStringChars + 1)}"`],
    ['not a string', 5],
  ];
  it('accepts ordinary type syntax', () => { for (const t of ok) assert.equal(checkTypeText(t), t, t); });
  for (const [why, text] of refused) {
    it(`refuses ${why}`, () => assert.throws(() => checkTypeText(text), TypeError));
    it(`describeRootTypes does not write ${why}`, () => {
      assert.throws(() => describeRootTypes({ root: 'window', allow: { get: ['window.a'] }, types: { 'window.a': { value: text } } }), TypeError);
    });
  }
  it('the whole map is bounded: entries and total characters', () => {
    const many = Object.fromEntries(Array.from({ length: TYPE_TEXT_LIMITS.maxEntries + 1 }, (_, i) => [`window.a${i}`, { value: 'string' }]));
    assert.throws(() => describeRootTypes({ root: 'window', allow: { get: ['window.**'] }, types: many }), /more than/);
    const heavy = Object.fromEntries(Array.from({ length: 40 }, (_, i) => [`window.a${i}`, { value: `"${'x'.repeat(190)}" | ${'string | '.repeat(100)}number` }]));
    assert.throws(() => describeRootTypes({ root: 'window', allow: { get: ['window.**'] }, types: heavy }), /together|over/);
  });
});

describe('the host: the types answer is the allow-lists narrowed by the key, and the type map is checked when the host is created', () => {
  const roots = () => ({ window: { document: { title: 'Shop' } }, store: { count: 1 } });
  const options = (extra = {}) => ({ roots: roots(), allow: { ...ALLOW, get: [...ALLOW.get, 'store.count'] }, eventFields: EVENT_FIELDS, types: TYPES, ...extra });

  async function bare(opts, who) {
    const [c, s] = createDuplexPair(who ? { permit: who } : {});
    createObjectsServer(opts).attach(s, { who: { username: 'alice', fingerprint: 'ab' } });
    closers.push(async () => { c.close(); s.close(); });
    return createObjectsClient(c);
  }

  it('answers for one root with that root\'s entries, the type map, and the event fields of the types the key may subscribe to; nothing of another root', async () => {
    const page = await bare(options());
    const d = await rootDescription(page.window);
    assert.equal(d.root, 'window');
    assert.deepEqual(d.ops, ['get', 'call', 'set', 'on']);
    assert.ok(d.allow.get.includes('window.document.title'));
    assert.ok(!d.allow.get.includes('store.count'), 'another root\'s entry is not told');
    assert.ok(d.allow.call.includes('window.app.subscribe(callback)'));
    assert.ok(d.allow.on.includes('window.hash@hashchange'));
    assert.deepEqual(Object.keys(d.types).sort(), Object.keys(TYPES).sort());
    assert.deepEqual(Object.keys(d.eventFields).sort(), ['*', 'hashchange']);
    assert.match(describeRootTypes(d), /RemoteCall<\[item: \{ sku: string; qty\?: number \}\], number, unknown>/);
    const store = await rootDescription(page.store);
    assert.deepEqual(store.allow.get, ['store.count']);
    assert.deepEqual(store.types, {});
  });

  it('the key\'s capabilities narrow it: an operation the key does not hold is not in the answer, and neither is the type that belongs to it', async () => {
    const host = createMemoryHost({ auth: { authorizedKeys: `capabilities="objects:window:get" ${keyLine}` }, rpc: { 'wsh-objects': exposeObjects(options()) } });
    closers.push(() => host.close());
    const client = await host.connect({ username: 'alice', keyPair });
    closers.push(() => client.disconnect());
    const page = await client.openObjects();
    assert.deepEqual(Object.keys(page), ['window']);
    const d = await rootDescription(page.window);
    assert.deepEqual(d.ops, ['get']);
    assert.deepEqual(d.allow, { get: ALLOW.get, call: [], set: [], on: [] });
    assert.deepEqual(Object.keys(d.types).sort(), ['window.app.cart.items', 'window.document.title']);
    assert.deepEqual(d.eventFields, {});
    const text = describeRootTypes(d);
    assert.doesNotMatch(text.slice(text.indexOf('export type')), /RemoteCall|WithEvents|WithSet|makeBus|bus/);
  });

  it('a host that does not state the types feature (0.50.0) is not asked: a named error', async () => {
    const [c, s] = createDuplexPair();
    createObjectsServer(options()).attach(s);
    closers.push(async () => { c.close(); s.close(); });
    const asked = [];
    const request = c.request.bind(c);
    c.request = async (m, p, o) => { asked.push(m); const a = await request(m, p, o); return m === 'roots' ? { ...a, features: a.features.filter((f) => f !== 'types') } : a; };
    const page = await createObjectsClient(c);
    await rejects(rootDescription(page.window), (e) => e.reason === 'unsupported' && /did not say/.test(e.message));
    assert.ok(!asked.includes('types'));
  });

  it('rootDescription takes a root, not a path or a handle', async () => {
    const page = await bare(options());
    await assert.rejects(rootDescription(page.window.document), TypeError);
    await assert.rejects(rootDescription({}), TypeError);
  });

  it('the answer is bounded by what the transport carries: more than a message fits is a named limit, not a truncated answer', async () => {
    const [c, s] = createDuplexPair({ maxMessageBytes: 6000 });
    createObjectsServer(options({ roots: roots(), allow: { get: Array.from({ length: 400 }, (_, i) => `window.very.long.path.number.${i}.x`) }, types: {} })).attach(s);
    closers.push(async () => { c.close(); s.close(); });
    const page = await createObjectsClient(c);
    await rejects(rootDescription(page.window), (e) => e.reason === 'limit' && e.data.limit === 'maxValueBytes');
  });

  it('configuration: a type for a path the allow-lists do not name, a bad text and a wildcard path are refused when the host is created, with the rule', () => {
    const make = (types) => () => createObjectsServer(options({ types }));
    assert.throws(make({ 'window.hidden': { value: 'string' } }), /no get or set entry|no call entry|allows that path/);
    assert.throws(make({ 'window.app.cart.items': { value: "import('x')" } }), /import/);
    assert.throws(make({ 'window.app.*': { value: 'string' } }), /literal/);
    assert.throws(make({ 'window.app.cart.items': { size: 'string' } }), /value, args, result, data/);
    assert.throws(make('string'), /types must be/);
    assert.throws(make({ 'window.app.bus@nope': { data: 'string' } }), /allows that path|on entry/);
    assert.doesNotThrow(make(TYPES));
  });
});

