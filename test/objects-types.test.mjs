  it('test/types/fixtures/window-remote.d.ts', async () => {
    const expected = describeRootTypes(description(), { name: 'WindowRemote' });
    const actual = await readFile(new URL('./types/fixtures/window-remote.d.ts', import.meta.url), 'utf8');
    assert.equal(actual, expected);
  });
